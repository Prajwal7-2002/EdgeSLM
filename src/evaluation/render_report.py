"""Render REPORT.md from the recorded result files.

The report is generated rather than hand-written so the numbers in it can never
drift from the numbers the harness produced.

    python src/evaluation/run_ablation.py
    python src/edge/benchmark.py
    python src/evaluation/render_report.py
"""

import argparse
import json
from pathlib import Path

ABLATION = Path("results/ablation.json")
EDGE = Path("results/edge_benchmark.json")
OUTPUT = Path("REPORT.md")

LABELS = ("PUBLIC", "INTERNAL", "CONFIDENTIAL", "RESTRICTED")

# Order systems weakest-baseline-first so the table reads as an argument.
SYSTEM_ORDER = (
    "policy-only",
    "tfidf-logreg",
    "base-zero-shot",
    "base-guided",
    "lora-no-policy",
    "lora-policy",
    "onnx-fp32-no-policy",
    "onnx-int8-no-policy",
    "onnx-int8-perchannel-no-policy",
    "onnx-int8-safehead-no-policy",
)

DATASET_ORDER = (
    "generated-test",
    "realistic",
    "adversarial",
    "reviewed-heldout",
    "reviewed-seen",
)

BACKEND_ORDER = (
    "torch-cuda-fp16",
    "torch-cpu-fp32",
    "onnx-cpu-fp32",
    "onnx-cpu-int8",
    "onnx-cpu-int8-perchannel",
    "onnx-cpu-int8-safehead",
)

# A quantised build is only useful if it is both fast and still correct, so the
# report pairs each benchmarked backend with the system that scored its weights.
BACKEND_TO_SYSTEM = {
    "torch-cpu-fp32": "lora-no-policy",
    "torch-cuda-fp16": "lora-no-policy",
    "onnx-cpu-fp32": "onnx-fp32-no-policy",
    "onnx-cpu-int8": "onnx-int8-no-policy",
    "onnx-cpu-int8-perchannel": "onnx-int8-perchannel-no-policy",
    "onnx-cpu-int8-safehead": "onnx-int8-safehead-no-policy",
}


def percent(value):
    return "—" if value is None else f"{value * 100:.1f}%"


def ordered(keys, preferred):
    known = [k for k in preferred if k in keys]
    return known + [k for k in keys if k not in preferred]


def accuracy_table(ablation, datasets, systems):
    lines = ["| System | " + " | ".join(datasets) + " |"]
    lines.append("|" + "---|" * (len(datasets) + 1))
    for system in systems:
        cells = []
        for dataset in datasets:
            entry = ablation["systems"][system]["datasets"].get(dataset)
            if entry is None:
                cells.append("—")
                continue
            low, high = entry["wilson_95"]
            cells.append(
                f"{entry['accuracy'] * 100:.1f}% "
                f"<br><sub>[{low * 100:.0f}–{high * 100:.0f}]</sub>"
            )
        lines.append(f"| `{system}` | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def metric_table(ablation, datasets, systems, extract, formatter):
    lines = ["| System | " + " | ".join(datasets) + " |"]
    lines.append("|" + "---|" * (len(datasets) + 1))
    for system in systems:
        cells = []
        for dataset in datasets:
            entry = ablation["systems"][system]["datasets"].get(dataset)
            cells.append("—" if entry is None else formatter(extract(entry)))
        lines.append(f"| `{system}` | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def confusion_block(entry):
    lines = ["| actual \\ predicted | " + " | ".join(LABELS) + " | other |"]
    lines.append("|" + "---|" * (len(LABELS) + 2))
    for actual in LABELS:
        row = entry["confusion"].get(actual, {})
        cells = [str(row.get(label, 0)) for label in LABELS]
        other = sum(n for p, n in row.items() if p not in LABELS)
        lines.append(f"| **{actual}** | " + " | ".join(cells) + f" | {other} |")
    return "\n".join(lines)


def render(ablation, edge):
    meta = ablation["meta"]
    systems = ordered(ablation["systems"].keys(), SYSTEM_ORDER)
    datasets = ordered(meta["datasets"].keys(), DATASET_ORDER)
    held_out = [d for d in datasets if meta["datasets"][d]["held_out"]]

    out = []
    add = out.append

    add("# EdgeSLM Evaluation Report")
    add("")
    add(
        "Generated by `src/evaluation/render_report.py` from `results/`. "
        "Do not edit by hand."
    )
    add("")
    add(
        f"Adapter `{Path(meta['adapter']).as_posix()}` · device `{meta['device']}`"
        + (f" · {meta['gpu']}" if meta.get("gpu") else "")
        + f" · torch {meta['torch']}"
    )
    add("")

    add("## How to read this")
    add("")
    add(
        "Every number below comes from a recorded run, including the ones that "
        "make the fine-tuned model look unnecessary. The evaluation sets differ "
        "sharply in difficulty and in how much they can be trusted, so the "
        "per-set notes matter more than any single headline figure."
    )
    add("")

    add("## Evaluation sets")
    add("")
    add("| Set | n | Held out | What it is |")
    add("|---|---|---|---|")
    for name in datasets:
        info = meta["datasets"][name]
        flag = "yes" if info["held_out"] else "**no**"
        add(f"| `{name}` | {info['n']} | {flag} | {info['note']} |")
    add("")

    add("## Systems")
    add("")
    add("| System | Description |")
    add("|---|---|")
    for system in systems:
        add(f"| `{system}` | {ablation['systems'][system]['description']} |")
    add("")

    add("## Accuracy")
    add("")
    add("Bracketed ranges are 95% Wilson score intervals.")
    add("")
    add(accuracy_table(ablation, datasets, systems))
    add("")
    add(
        "> `reviewed-seen` is **training data**. Model scores on that column "
        "measure memorisation and must not be read as generalisation. It is "
        "included because dropping it would hide the contamination rather than "
        "quantify it."
    )
    add("")

    add("### Macro F1")
    add("")
    add(
        metric_table(
            ablation,
            datasets,
            systems,
            lambda e: e["macro_f1"],
            lambda v: f"{v:.3f}",
        )
    )
    add("")

    add("### RESTRICTED recall")
    add("")
    add(
        "The safety-critical metric: the share of credential-bearing documents "
        "the system correctly flags. A miss here is the failure the project "
        "exists to prevent."
    )
    add("")
    add(
        metric_table(
            ablation, datasets, systems, lambda e: e["restricted_recall"], percent
        )
    )
    add("")
    add("### RESTRICTED documents released as PUBLIC or INTERNAL")
    add("")
    add(
        "Counts, not rates. These are the individual documents a deployment "
        "would have under-classified."
    )
    add("")
    add(
        metric_table(
            ablation,
            datasets,
            systems,
            lambda e: e["restricted_under_classified"],
            lambda v: str(v),
        )
    )
    add("")

    policy = ablation["systems"].get("policy-only")
    if policy:
        add("## What the regex layer actually contributes")
        add("")
        add(
            "In the shipped configuration the policy layer runs *before* the "
            "model and short-circuits it whenever a rule matches, so its "
            "coverage sets a ceiling on how much the model can influence the "
            "answer."
        )
        add("")
        add("| Set | Rule fires on | Correct when it fires |")
        add("|---|---|---|")
        for name in datasets:
            entry = policy["datasets"].get(name)
            if not entry or "coverage" not in entry:
                continue
            cov = entry["coverage"]
            add(
                f"| `{name}` | {percent(cov['fire_rate'])} "
                f"({cov['fired_n']}/{entry['n']}) | "
                f"{percent(cov['accuracy_when_fired'])} |"
            )
        add("")

    add("## Confusion matrices on held-out data")
    add("")
    for system in systems:
        for name in held_out:
            entry = ablation["systems"][system]["datasets"].get(name)
            if entry is None:
                continue
            add(f"<details><summary><code>{system}</code> · {name}</summary>")
            add("")
            add(confusion_block(entry))
            add("")
            add(
                f"Non-answers (UNKNOWN/ABSTAIN): "
                f"{percent(entry['non_answer_rate'])}"
            )
            add("")
            add("</details>")
            add("")

    if edge:
        emeta = edge["meta"]
        backends = ordered(edge["backends"].keys(), BACKEND_ORDER)
        add("## Edge performance")
        add("")
        add(
            f"{emeta['processor'] or 'CPU'} · "
            f"{emeta['cpu_count_physical']} physical / "
            f"{emeta['cpu_count_logical']} logical cores"
            + (f" · {emeta['gpu']}" if emeta.get("gpu") else "")
        )
        add("")
        add(emeta["note"])
        add("")
        add(
            f"{emeta['measurements_per_backend']} timed calls per backend "
            f"({emeta['documents']} documents × {emeta['repeats']} repeats, "
            f"{emeta['warmup']} warmup calls discarded)."
        )
        add("")
        add(
            "| Backend | p50 | p95 | mean | docs/s | Load | Artifact | Peak RSS |"
        )
        add("|---|---|---|---|---|---|---|---|")
        for name in backends:
            b = edge["backends"][name]
            lat = b["latency_ms"]
            artifact = (
                f"{b['artifact_mb']} MB" if b.get("artifact_mb") else "—"
            )
            add(
                f"| `{name}` | {lat['p50']} ms | {lat['p95']} ms | "
                f"{lat['mean']} ms | {b['throughput_docs_per_sec']} | "
                f"{b['load_seconds']} s | {artifact} | "
                f"{b['process_rss_mb']} MB |"
            )
        add("")

        add("### Does quantisation keep the model correct?")
        add("")
        add(
            "Speed is only worth having if the answers survive it, so each "
            "benchmarked build is paired here with its accuracy from the same "
            "weights."
        )
        add("")
        add("| Backend | p50 | Artifact | Accuracy on `reviewed-heldout` |")
        add("|---|---|---|---|")
        for name in backends:
            system = BACKEND_TO_SYSTEM.get(name)
            entry = (
                ablation["systems"].get(system, {})
                .get("datasets", {})
                .get("reviewed-heldout")
            )
            b = edge["backends"][name]
            accuracy = "—" if entry is None else percent(entry["accuracy"])
            artifact = f"{b['artifact_mb']} MB" if b.get("artifact_mb") else "—"
            add(
                f"| `{name}` | {b['latency_ms']['p50']} ms | {artifact} | "
                f"{accuracy} |"
            )
        add("")

    add("## Reproducing")
    add("")
    add("```bash")
    add("python src/evaluation/merge_annotations.py   # build the reviewed set")
    add("python src/evaluation/run_ablation.py        # results/ablation.json")
    add("python src/edge/export_onnx.py               # ONNX + INT8 builds")
    add("python src/edge/benchmark.py                 # results/edge_benchmark.json")
    add("python src/evaluation/render_report.py       # this file")
    add("```")
    add("")

    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--ablation", type=Path, default=ABLATION)
    parser.add_argument("--edge", type=Path, default=EDGE)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()

    if not args.ablation.exists():
        raise SystemExit(f"{args.ablation} not found; run run_ablation.py first")

    ablation = json.loads(args.ablation.read_text(encoding="utf-8"))
    edge = (
        json.loads(args.edge.read_text(encoding="utf-8"))
        if args.edge.exists()
        else None
    )
    if edge is None:
        print(f"NOTE: {args.edge} not found; skipping the edge section")

    args.output.write_text(render(ablation, edge), encoding="utf-8")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
